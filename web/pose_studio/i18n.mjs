const textOriginals = new WeakMap();
const attributeOriginals = new WeakMap();
const roots = new Set();
let installed = false;
let localeSetting;
let previousOnChange;

function currentLocale(app) {
    return String(app?.ui?.settings?.getSettingValue?.("Comfy.Locale") || "en").toLowerCase();
}

function translate(value, locale) {
    if (!locale.startsWith("zh")) return value;
    if (ZH[value] != null) return ZH[value];
    let match = value.match(/^(Pose|Open Pose|Delete Pose) (\d+)$/);
    if (match) return `${match[1] === "Delete Pose" ? "删除姿势" : match[1] === "Open Pose" ? "打开姿势" : "姿势"} ${match[2]}`;
    match = value.match(/^Add Character (\d+)$/);
    if (match) return `添加角色 ${match[1]}`;
    match = value.match(/^Select (Character \d+)$/);
    if (match) return `选择角色 ${match[1].slice("Character ".length)}`;
    match = value.match(/^Character (\d+) model color$/);
    if (match) return `角色 ${match[1]} 模型颜色`;
    match = value.match(/^Remove Character (\d+)\?$/);
    if (match) return `移除角色 ${match[1]}？`;
    match = value.match(/^Character (\d+) selected$/);
    if (match) return `已选择角色 ${match[1]}`;
    match = value.match(/^Add Character (\d+)$/);
    if (match) return `添加角色 ${match[1]}`;
    return value;
}

function translateTextNode(node, locale) {
    const current = node.nodeValue;
    if (!current || !current.trim()) return;
    const parent = node.parentElement;
    if (parent?.closest("input,textarea,[contenteditable=true],script,style")) return;
    const state = textOriginals.get(node);
    let original;
    if (state && current === state.localized) original = state.original;
    else original = current;
    const leading = original.match(/^\s*/)?.[0] || "";
    const trailing = original.match(/\s*$/)?.[0] || "";
    const value = original.trim();
    const localized = translate(value, locale);
    const next = leading + localized + trailing;
    textOriginals.set(node, { original, localized: next });
    if (current !== next) node.nodeValue = next;
}

function translateAttributes(element, locale) {
    for (const name of ["title", "placeholder", "aria-label"]) {
        if (!element.hasAttribute(name)) continue;
        const current = element.getAttribute(name);
        let state = attributeOriginals.get(element);
        if (!state) attributeOriginals.set(element, state = {});
        let item = state[name];
        const original = item && current === item.localized ? item.original : current;
        const localized = translate(original, locale);
        state[name] = { original, localized };
        if (current !== localized) element.setAttribute(name, localized);
    }
}

function translateSubtree(root, locale) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = root;
    while (node) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, locale);
        else translateAttributes(node, locale);
        node = walker.nextNode();
    }
}

function updateAll(app) {
    const locale = currentLocale(app);
    for (const root of roots) if (root.isConnected) translateSubtree(root, locale);
}

export function observePoseStudioI18n(root, app) {
    if (!root || !app) return () => {};
    roots.add(root);
    if (!installed) {
        localeSetting = app.ui?.settings?.settingsLookup?.["Comfy.Locale"];
        previousOnChange = localeSetting?.onChange;
        if (localeSetting) {
            localeSetting.onChange = function (...args) {
                const result = previousOnChange?.apply(this, args);
                updateAll(app);
                return result;
            };
        }
        installed = true;
    }
    const observer = new MutationObserver(records => {
        const locale = currentLocale(app);
        for (const record of records) {
            if (record.type === "characterData") translateTextNode(record.target, locale);
            else if (record.type === "attributes") translateAttributes(record.target, locale);
            else for (const node of record.addedNodes) {
                if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, locale);
                else if (node.nodeType === Node.ELEMENT_NODE) translateSubtree(node, locale);
            }
        }
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["title", "placeholder", "aria-label"] });
    translateSubtree(root, currentLocale(app));
    return () => {
        observer.disconnect();
        roots.delete(root);
    };
}

export function translatePoseStudioSubtree(root, app) {
    if (!root || !app) return;
    translateSubtree(root, currentLocale(app));
}
