const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const source = fs.readFileSync(path.join(__dirname, '../web/xzg_image_pose_editor_ctrl_character_controls.js'), 'utf8');
const core = fs.readFileSync(path.join(__dirname, '../web/pose_studio/core.js'), 'utf8');
const part = (s, a, b) => s.slice(s.indexOf(a), s.indexOf(b, s.indexOf(a)));
const ui = part(source, '        // Lighting Section', '    _setupFinalUI()').replace(/\n    }\s*$/, '');
const methods = part(source, '    defaultLightParams()', '    updateRotationSliders()');
const lights = part(core, '    updateLights(lightParams)', '    animate()');
(async () => {
 const browser = await chromium.launch({ channel: 'chrome', headless: true });
 try {
  const page = await browser.newPage({viewport:{width:800,height:800}});
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.route('http://pose.test/**', route => route.fulfill({contentType: route.request().url().endsWith('.js') ? 'text/javascript' : 'text/html', body: route.request().url().endsWith('.js') ? fs.readFileSync(path.join(__dirname, '../web/vnccs_pose_vendor/three/three.module.js'), 'utf8') : '<html><body></body></html>'}));
  await page.goto('http://pose.test/');
  await page.evaluate(async ({ui, methods, lights, history}) => {
   const THREE = await import('/three.js');
   const xzgTh = (zh, en) => zh;
   const Widget = new Function('xzgTh', `return class { build() { const rightSidebar = this.rightSidebar; ${ui} } ${methods} }`)(xzgTh);
   const Viewer = new Function(`return class { ${lights} ${history} }`)();
   const scene = new THREE.Scene();
   const renderer = new THREE.WebGLRenderer({preserveDrawingBuffer:true});
   renderer.setSize(128,128);
   const camera = new THREE.PerspectiveCamera(45,1,0.1,100); camera.position.z=5;
   scene.add(new THREE.Mesh(new THREE.SphereGeometry(1,32,24),new THREE.MeshPhongMaterial({color:0xffffff})));
   const sidebar = document.createElement('div'); sidebar.style.width='260px'; document.body.append(sidebar);
   const viewer = new Viewer(); Object.assign(viewer, {THREE,scene,initialized:true,lights:[],history:[],future:[],maxHistory:50, requestRender(){renderer.render(scene,camera);},isInitialized(){return true;},getPose(){return {};},setPose(){},dispatchPoseChange(){}});
   const w = new Widget(); Object.assign(w,{rightSidebar:sidebar,exportParams:{},viewer, syncToNode(){window.saved=JSON.stringify({lights:this.lightParams,export:this.exportParams});},createSection(title){const el=document.createElement('section');const h=document.createElement('h3');h.textContent=title;const content=document.createElement('div');el.append(h,content);return {el,content};}});
   w.lightParams=w.defaultLightParams();
   viewer.options={captureHistoryContext:()=>({lights:structuredClone(w.lightParams)}), onHistoryRestore:pose=>{w.lightParams=pose.editorState.lights;w.refreshLightUI();w.applyLighting();}};
   w.build();w.applyLighting();
   window.w=w;window.renderer=renderer;
  }, {ui, methods, lights, history:part(core,'    getHistoryPose()', '    setPose(pose,')});
  assert.equal(await page.locator('.vnccs-ps-light-card').count(),2);
  const before=await page.evaluate(()=>renderer.domElement.toDataURL());
  await page.locator('.vnccs-ps-light-color').nth(1).fill('#ff0000');
  const after=await page.evaluate(()=>renderer.domElement.toDataURL());
  assert.notEqual(before,after,'Changing light color must change rendered pixels');
  await page.getByText('+ 添加光源',{exact:true}).click();
  assert.equal(await page.locator('.vnccs-ps-light-card').count(),3);
  await page.locator('.vnccs-ps-light-select').nth(2).selectOption('point');
  assert.equal(await page.locator('.vnccs-ps-light-card').nth(2).locator('.vnccs-ps-light-slider').count(),2);
  const radar=page.locator('.vnccs-ps-light-radar-canvas').last();
  await radar.click({position:{x:75,y:25}});
  const position=await page.evaluate(()=>w.lightParams[2]);
  assert.ok(position.x>0 && position.z<0);
  await page.locator('.vnccs-ps-light-remove').last().click();
  assert.equal(await page.locator('.vnccs-ps-light-card').count(),2);
  await page.evaluate(()=>w.viewer.undo());
  assert.equal(await page.locator('.vnccs-ps-light-card').count(),3);
  assert.equal(await page.evaluate(()=>w.lightParams[2].type),'point');
  await page.evaluate(()=>w.viewer.redo());
  assert.equal(await page.locator('.vnccs-ps-light-card').count(),2);
  await page.getByText('均匀白光：已关闭',{exact:true}).click();
  assert.equal(await page.evaluate(()=>w.viewer.lights[0].intensity),1);
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(()=>JSON.parse(saved).export.keepOriginalLighting),true);
  assert.deepEqual(errors,[]);
  console.log('Lighting browser test: UI, point radius, radar position, live WebGL pixels, removal undo/redo, flat lighting, serialization passed.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
